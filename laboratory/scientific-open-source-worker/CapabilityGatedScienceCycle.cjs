"use strict";
/**
 * Capability-gated, source-first scientific cycle.
 * Only emits executable protocols when an exact reviewed fixture exists.
 * This is a deterministic planner, not an arbitrary Solidity/EVM runner.
 */
const assert=require("node:assert/strict");
const crypto=require("node:crypto");
const fs=require("node:fs");
const path=require("node:path");
const hash=b=>crypto.createHash("sha256").update(b).digest("hex");
const canonical=x=>hash(Buffer.from(JSON.stringify(x)));
const hex64=x=>typeof x==="string"&&/^[a-f0-9]{64}$/.test(x);
const txHash=x=>typeof x==="string"&&/^0x[a-f0-9]{64}$/i.test(x);
const pairKey=x=>x.map(s=>s.id).join("|");
const SUPPORTED="ERC-8098|ERC-4626";
const VAULT_ASSET="ERC-4626|ERC-20";
const {assessVaultAssetFixture,concludeVaultAsset}=require("./VaultAssetCapabilityAdapter.cjs");

function requireSourceEvidence({graph,discovery,feasibility,report}){
  assert.equal(graph?.schemaVersion,"OECL_SOLIDITY_COMPILER_AST_GRAPH_V1");
  assert.equal(discovery?.schemaVersion,"OECL_GENERIC_AST_HYPOTHESES_V1");
  assert.equal(report?.schemaVersion,"OECL_OPEN_GENERIC_AST_RESULT_V1");
  assert.equal(report.sourceOnly,true);
  assert.equal(report.evmExecuted,false);
  assert.equal(report.scientificVerdict,"INCONCLUSIVE");
  assert.equal(report.candidateAdmission,"NOT_ADMITTED");
  assert.equal(discovery.verdict,"INCONCLUSIVE");
  assert.equal(discovery.candidateAdmission,"NOT_ADMITTED");
  assert.deepEqual(discovery.errors,[]);
  assert(Array.isArray(discovery.hypotheses)&&discovery.hypotheses.length<=128);
  assert(Array.isArray(report.selected)&&report.selected.length===2);
  assert(report.selected[0].id!==report.selected[1].id);
  assert(report.selected.every(s=>typeof s.id==="string"&&
    hex64(s.sourceSha256)&&typeof s.revision==="string"));
  assert.equal(report.graphSha256,canonical(graph));
  assert.equal(discovery.sourceGraphSha256,report.graphSha256);
  assert.equal(feasibility?.sourceGraphSha256,report.graphSha256);
  assert.equal(report.hypothesisArtifactSha256,canonical(discovery));
  assert.equal(report.pathFeasibilityArtifactSha256,canonical(feasibility));
  assert.equal(feasibility.discoverySha256,canonical(discovery));
  assert.deepEqual(report.hypotheses,discovery.hypotheses);
  assert(Array.isArray(feasibility.hypotheses));
  for(const h of discovery.hypotheses){
    assert(/^AST-HYP-[a-f0-9]{24}$/.test(h.hypothesisId));
    assert.equal(h.status,"SOURCE_ONLY_UNEVALUATED");
    assert.equal(h.scientificVerdict,"INCONCLUSIVE");
    assert.equal(h.candidateAdmission,"NOT_ADMITTED");
    assert(feasibility.hypotheses.some(f=>f.hypothesisId===h.hypothesisId),
      "Missing corresponding AST path-screen");
  }
}

function assessReviewedFixture(x){
  const {report,discovery,feasibility,original,challenges,originalBytes,challengeBytes,reportBytes,discoveryBytes}=x;
  if(!original||!challenges||!originalBytes||!challengeBytes)
    return {ready:false,reason:"PINNED_SOURCE_PLAN_OR_FALSIFIERS_MISSING"};
  assert.equal(original.schemaVersion,"OECL_AUTOGENERATED_PINNED_AST_HYPOTHESIS_EXPERIMENT_V1");
  assert.equal(challenges.schemaVersion,"OECL_AST_SELF_FALSIFICATION_PLAN_V1");
  assert.equal(original.originatedBy,"OECL_GENERIC_AST_HYPOTHESES_V1");
  assert.equal(original.preparedBeforeEvmDeployment,true);
  assert.equal(original.sourceOnlyBeforeExperiment,true);
  assert.equal(original.evmExecuted,false);
  assert.equal(original.provenance.reportSha256,hash(reportBytes));
  assert.equal(original.provenance.discoverySha256,hash(discoveryBytes));
  assert.equal(original.provenance.graphSha256,report.graphSha256);
  assert.deepEqual(original.provenance.sources,report.selected);
  assert.equal(challenges.sourcePlanSha256,hash(originalBytes));
  assert.equal(challenges.sourceGraphSha256,report.graphSha256);
  assert.equal(challenges.originHypothesisId,original.originHypothesisId);
  assert.equal(challenges.experimentId,original.experimentId);
  assert.equal(challenges.generatedBeforeEvmDeployment,true);
  assert.equal(challenges.emulatedEvmOrReceipt,false);
  assert.equal(challenges.compatibilityVerdict,"NOT_EVALUATED");
  assert.equal(challenges.candidateAdmission,"NOT_ADMITTED");

  const hypotheses=discovery.hypotheses.filter(h=>h.kind==="POTENTIAL_COUPLED_STATE_DECREASE");
  assert.equal(hypotheses.length,1,"Ambiguous AST origin is not independently testable");
  const h=hypotheses[0];
  assert.equal(h.hypothesisId,original.originHypothesisId);
  assert.equal(original.originHypothesisKind,h.kind);
  assert.equal(feasibility.hypotheses.find(f=>f.hypothesisId===h.hypothesisId)?.pathScreen,
    "NOT_PROVEN_EXECUTABLE","AST reachability cannot be promoted to proven execution");
  assert.deepEqual(report.selected.map(s=>s.id),["ERC-8098","ERC-4626"]);
  assert.equal(original.predictions?.length,2);
  assert.equal(challenges.challenges?.length,4);
  const operations=["BURN_UNDERLYING","REDEEM_SHARES"];
  const entries=["burn","redeem"];
  const seen=new Set();
  for(let i=0;i<2;i++){
    const p=original.predictions[i],e=h.evidence?.[i],source=report.selected[i];
    assert(p&&e);
    assert.equal(p.parentAstHypothesisId,h.hypothesisId);
    assert.equal(p.participant,source.id);
    assert.equal(e.participant,source.id);
    assert.equal(p.operation,operations[i]);
    assert.equal(p.publicEntrypoint,entries[i]);
    assert.equal(e.publicEntrypoint?.name,entries[i]);
    assert.equal(p.stateVar,"_totalSupply");
    assert.equal(e.stateDecrease?.state,"_totalSupply");
    assert.equal(p.stateSourceSha256,e.stateDecrease.sourceSha256);
    assert.equal(p.publicEntrypointSourceSha256,e.publicEntrypoint.sourceSha256);
    assert.equal(p.sourceRevision,source.revision);
    assert.equal(p.sourceRootSha256,source.sourceSha256);
    assert.deepEqual(p.callPath,e.callPath);
    assert.equal(p.requiredNumericRelation,"STRICTLY_LESS_THAN");
    const owned=challenges.challenges.filter(c=>c.originalScopedPredictionId===p.predictionId);
    assert.equal(owned.length,2);
    for(const [j,kind] of ["ZERO_AMOUNT_BOUNDARY","ABOVE_OWNED_BALANCE"].entries()){
      const c=owned[j];
      assert.equal(c.challengeKind,kind);
      assert.equal(c.quantityRule,j===0?"ZERO":"OWNED_TOKEN_BALANCE_PLUS_ONE");
      assert.equal(c.originHypothesisId,h.hypothesisId);
      assert.equal(c.operation,p.operation);
      assert.equal(c.sourceSha256,p.stateSourceSha256);
      assert.equal(c.sourceRevision,p.sourceRevision);
      assert.equal(c.status,"CHALLENGE_PROPOSED_NOT_EVM_TESTED");
      assert.equal(c.contestedGeneralization,j===0?
        "EVERY_SUCCESSFUL_CALL_STRICTLY_DECREASES_TOTAL_SUPPLY":
        "PUBLIC_ENTRYPOINT_ALWAYS_EXECUTABLE");
      assert(!seen.has(c.caseId));seen.add(c.caseId);
    }
  }
  return {ready:true,adapter:"PINNED_8098_4626_LOCAL_HARDHAT_ONLY",
    originHypothesisId:h.hypothesisId,sourcePlanSha256:hash(originalBytes),
    challengePlanSha256:hash(challengeBytes),
    testIds:challenges.challenges.map(c=>c.caseId),
    positivePredictionIds:original.predictions.map(p=>p.predictionId)};
}

function buildPlan(x){
  requireSourceEvidence(x);
  const {report,discovery,feasibility}=x;
  const selected=report.selected.map(s=>({id:s.id,revision:s.revision,sourceSha256:s.sourceSha256}));
  const proposals=discovery.hypotheses.map(h=>{
    const screen=feasibility.hypotheses.find(f=>f.hypothesisId===h.hypothesisId);
    const isState=h.kind==="POTENTIAL_COUPLED_STATE_DECREASE";
    return {
      hypothesisId:h.hypothesisId,kind:h.kind,
      question:isState?
        "Does each specific authorized positive-quantity entrypoint decrease its own observed state?":
        "Does shared inheritance imply the same concrete behavior under independent implementation controls?",
      wouldChallenge:isState?
        "Mined eligible positive-quantity execution with an unchanged tracked state variable":
        "A source-pinned behavioral difference between two implementations sharing the inherited base",
      pathScreen:screen.pathScreen,
      sourceEvidence:h.evidence,
      testStatus:"NOT_EXECUTED",
      epistemicStatus:"SOURCE_HYPOTHESIS_ONLY"
    };
  });
  let fixture={ready:false,reason:"NO_REVIEWED_EVM_ADAPTER"};
  if(pairKey(report.selected)===SUPPORTED)
    fixture=assessReviewedFixture(x);
  else if(pairKey(report.selected)===VAULT_ASSET)
    fixture=assessVaultAssetFixture(x);
  const verdict=proposals.length===0?"NO_AST_HYPOTHESIS_OBSERVED":
    fixture.ready?"REVIEWED_LOCAL_EVM_PROTOCOL_PREREGISTERED":
    "BLOCKED_REVIEWED_ADAPTER_REQUIRED";
  return {
    schemaVersion:"OECL_CAPABILITY_GATED_SCIENCE_CYCLE_V1",
    generationMethod:"DETERMINISTIC_COMPILER_AST_TO_CAPABILITY_GATED_FALSIFIERS",
    selected,
    provenance:{graphSha256:report.graphSha256,
      reportSha256:hash(x.reportBytes),discoverySha256:hash(x.discoveryBytes)},
    proposals,fixture,workflowStatus:verdict,
    localEvmExecuted:false,
    scope:"SOURCE_ONLY_UNTIL_INDEPENDENT_REPLAY",
    scientificVerdict:"INCONCLUSIVE",
    compatibilityVerdict:"NOT_EVALUATED",
    candidateAdmission:"NOT_ADMITTED",
    limitations:[
      "The planner generates conditional falsifiers, not a universal scientific explanation.",
      "Only immutable reviewed ERC-8098/4626 and ERC-4626/20 fixtures have registered local-EVM executors.",
      "AST reachability is not proof that a path is executable.",
      "No EVM outcome or universal compatibility is inferred from this plan."
    ]
  };
}

function conclude(x){
  const {plan,review,positiveBytes,counterfactualBytes,originalBytes,challengeBytes}=x;
  assert.equal(plan?.schemaVersion,"OECL_CAPABILITY_GATED_SCIENCE_CYCLE_V1");
  assert.equal(plan.localEvmExecuted,false);
  assert.equal(plan.compatibilityVerdict,"NOT_EVALUATED");
  assert.equal(plan.candidateAdmission,"NOT_ADMITTED");
  if(!plan.fixture.ready||!review){
    return {schemaVersion:"OECL_SCIENTIFIC_CYCLE_CONCLUSION_V1",
      selected:plan.selected,cycleStatus:"UNRESOLVED",
      reason:!plan.fixture.ready?plan.fixture.reason:"INDEPENDENT_EVM_REPLAY_MISSING",
      scopedConclusions:[],scientificVerdict:"INCONCLUSIVE",
      compatibilityVerdict:"NOT_EVALUATED",candidateAdmission:"NOT_ADMITTED",
      evmEvidenceAdmitted:false};
  }
  assert.equal(plan.fixture.adapter,"PINNED_8098_4626_LOCAL_HARDHAT_ONLY");
  assert.equal(plan.fixture.sourcePlanSha256,hash(originalBytes));
  assert.equal(plan.fixture.challengePlanSha256,hash(challengeBytes));
  assert.equal(review.schemaVersion,"OECL_INDEPENDENT_AST_SELF_FALSIFICATION_REVIEW_V1");
  assert.equal(review.sourceHypothesisId,plan.fixture.originHypothesisId);
  assert.equal(review.sourceGraphSha256,plan.provenance.graphSha256);
  assert.equal(review.counterfactualPlanSha256,hash(challengeBytes));
  assert.equal(review.positiveEvmArtifactSha256,hash(positiveBytes));
  assert.equal(review.counterfactualEvmArtifactSha256,hash(counterfactualBytes));
  assert.equal(review.scope,"SCIENCE_REFUTES_OVERBROAD_INFERENCE_NOT_ORIGINAL_SCOPED_AST_OBSERVATION");
  assert.equal(review.scientificVerdict,"INCONCLUSIVE");
  assert.equal(review.globalCompatibilityVerdict,"NOT_EVALUATED");
  assert.equal(review.candidateAdmission,"NOT_ADMITTED");
  assert.equal(review.receiptAuthentication,"NOT_PERFORMED_BY_THIS_REPLAY");
  assert.equal(review.refinedHypotheses?.length,2);
  assert.equal(review.cases?.length,4);
  const expected=new Set(plan.fixture.positivePredictionIds);
  const scopedConclusions=[];
  for(const p of review.refinedHypotheses){
    assert(expected.delete(p.scopedPredictionId),"Duplicate or substituted prediction");
    assert.equal(p.originalAstHypothesisId,plan.fixture.originHypothesisId);
    assert.equal(p.originalAstFindingStillValid,true);
    assert.equal(p.epistemicStatus,
      "CONDITIONALLY_SUPPORTED_WITH_FALSIFIED_OVERGENERALIZATIONS");
    assert.equal(p.supportedObservation?.strictlyDecreasedForPositiveAmount,true);
    assert(txHash(p.supportedObservation?.localMinedReceipt));
    assert(BigInt(p.supportedObservation?.measuredAfter)<
      BigInt(p.supportedObservation?.measuredBefore));
    assert.equal(p.falsifyingObservations?.length,2);
    const zero=p.falsifyingObservations.find(z=>
      z.claimRefuted==="EVERY_SUCCESSFUL_CALL_STRICTLY_DECREASES_TOTAL_SUPPLY");
    const over=p.falsifyingObservations.find(z=>
      z.claimRefuted==="PUBLIC_ENTRYPOINT_ALWAYS_EXECUTABLE");
    assert(txHash(zero?.localMinedReceipt));
    assert.equal(over?.unminedCallStaticRevert,true);
    assert(review.cases.some(c=>c.caseId===zero.caseId&&
      c.scientificChallengeStatus==="REFUTED_OVERBROAD_CLAIM"));
    assert(review.cases.some(c=>c.caseId===over.caseId&&
      c.scientificChallengeStatus==="EXECUTABILITY_OVERCLAIM_REFUTED"));
    scopedConclusions.push({
      originalAstHypothesisId:p.originalAstHypothesisId,
      predictionId:p.scopedPredictionId,
      conclusion:"SCOPED_POSITIVE_SUPPORTED_BUT_UNIVERSAL_OVERCLAIMS_REFUTED",
      positiveLocalReceipt:p.supportedObservation.localMinedReceipt,
      zeroQuantityCounterexampleReceipt:zero.localMinedReceipt,
      aboveBalanceControl:"UNMINED_CALLSTATIC_REVERT",
      originalAstHypothesisFalsified:false
    });
  }
  assert.equal(expected.size,0);
  assert.equal(review.cases.filter(c=>plan.fixture.testIds.includes(c.caseId)).length,4);
  return {schemaVersion:"OECL_SCIENTIFIC_CYCLE_CONCLUSION_V1",
    selected:plan.selected,cycleStatus:"CONTROLLED_LOCAL_EVM_AND_REPLAY_COMPLETE",
    scopedConclusions,
    provenance:{sourcePlanSha256:hash(originalBytes),
      challengePlanSha256:hash(challengeBytes),
      positiveEvmSha256:hash(positiveBytes),
      counterfactualEvmSha256:hash(counterfactualBytes)},
    scientificVerdict:"INCONCLUSIVE",
    compatibilityVerdict:"NOT_EVALUATED",candidateAdmission:"NOT_ADMITTED",
    evmEvidenceAdmitted:true,
    receiptAuthentication:"LOCAL_PROVIDER_VERIFIED_BY_RUNNER_NOT_INDEPENDENT_MAINNET",
    limitations:["The scientist's challenges refute overbroad generalizations, not the original AST structural finding.",
      "Execution depended on one explicitly reviewed and pinned Hardhat fixture.",
      "Unmined negative calls cannot be described as mined transaction receipts.",
      "No global interoperability or production security assertion is made."]
  };
}
const load=(dir,n)=>{const bytes=fs.readFileSync(path.join(dir,n+".json"));return {bytes,value:JSON.parse(bytes)};};
function planFolder(dir){
  const graph=load(dir,"structural-ast-graph");
  const discovery=load(dir,"generic-source-hypotheses");
  const feasibility=load(dir,"path-feasibility");
  const report=load(dir,"source-scientific-report");
  const original=fs.existsSync(path.join(dir,"ast-derived-preregistered-plan.json"))?
    load(dir,"ast-derived-preregistered-plan"):null;
  const challenge=fs.existsSync(path.join(dir,"ast-self-falsification-plan.json"))?
    load(dir,"ast-self-falsification-plan"):null;
  const plan=buildPlan({graph:graph.value,discovery:discovery.value,
    feasibility:feasibility.value,report:report.value,
    original:original?.value,challenges:challenge?.value,
    originalBytes:original?.bytes,challengeBytes:challenge?.bytes,
    reportBytes:report.bytes,discoveryBytes:discovery.bytes});
  fs.writeFileSync(path.join(dir,"capability-gated-scientific-cycle.json"),
    JSON.stringify(plan,null,2)+"\n");
  return plan;
}
function main(args){
  if(args[0]==="plan"){
    const root=path.resolve(args[1]||"source-output");
    const dirs=fs.readdirSync(root,{withFileTypes:true}).filter(d=>
      d.isDirectory()&&d.name.startsWith("pair-")).map(d=>path.join(root,d.name)).sort();
    assert(dirs.length>0&&dirs.length<=100,"No bounded source pair cohort");
    const statuses=dirs.map(dir=>({pair:path.basename(dir),
      status:planFolder(dir).workflowStatus}));
    console.log("OECL_CAPABILITY_GATED_SOURCE_PLANS",JSON.stringify(statuses));
  }else if(args[0]==="conclude"){
    const folder=path.resolve(args[1]||"source-output/pair-8098-4626");
    const reviewFile=path.resolve(args[2]||"audit-output/scientist-ast-self-falsification-review.json");
    const out=path.resolve(args[3]||"audit-output/scientist-capability-gated-cycle.json");
    const p=load(folder,"capability-gated-scientific-cycle").value;
    const review=fs.existsSync(reviewFile)?JSON.parse(fs.readFileSync(reviewFile)):null;
    const result=conclude({plan:p,review,
      originalBytes:load(folder,"ast-derived-preregistered-plan").bytes,
      challengeBytes:load(folder,"ast-self-falsification-plan").bytes,
      positiveBytes:load(folder,"ast-hypothesis-experiment").bytes,
      counterfactualBytes:load(folder,"ast-self-falsification-evm").bytes});
    fs.mkdirSync(path.dirname(out),{recursive:true});
    fs.writeFileSync(out,JSON.stringify(result,null,2)+"\n");
    console.log("OECL_CAPABILITY_GATED_CONCLUSION",result.cycleStatus,
      "scoped",result.scopedConclusions.length);
  }else if(args[0]==="conclude-vault"){
    const folder=path.resolve(args[1]||"source-output/pair-4626-20");
    const out=path.resolve(args[2]||"audit-output/scientist-vault-asset-capability-cycle.json");
    const planFile=load(folder,"capability-gated-scientific-cycle");
    const source={
      graph:load(folder,"structural-ast-graph"),
      discovery:load(folder,"generic-source-hypotheses"),
      feasibility:load(folder,"path-feasibility"),
      report:load(folder,"source-scientific-report")
    };
    const sourcePlan=buildPlan({
      graph:source.graph.value,
      discovery:source.discovery.value,
      feasibility:source.feasibility.value,
      report:source.report.value,
      reportBytes:source.report.bytes,
      discoveryBytes:source.discovery.bytes
    });
    const evm=fs.existsSync(path.join(folder,"independent-local-evm.json"))?
      load(folder,"independent-local-evm"):null;
    const result=concludeVaultAsset({
      plan:planFile.value,planBytes:planFile.bytes,
      sourcePlan,evm:evm?.value,evmBytes:evm?.bytes
    });
    fs.mkdirSync(path.dirname(out),{recursive:true});
    fs.writeFileSync(out,JSON.stringify(result,null,2)+"\n");
    console.log("OECL_VAULT_ASSET_SCIENTIST_CONCLUSION",result.status,
      "scoped",result.scopedConclusions.length);
  }else throw Error("Usage: CapabilityGatedScienceCycle.cjs plan <root> | conclude <8098-pair-folder> <review.json> <output.json> | conclude-vault <4626-pair-folder> <output.json>");
}
if(require.main===module)main(process.argv.slice(2));
module.exports={buildPlan,conclude,planFolder};
