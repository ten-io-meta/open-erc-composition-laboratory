"use strict";
const fs=require("node:fs");
const path=require("node:path");
const crypto=require("node:crypto");
const assert=require("node:assert/strict");
const sha256=x=>crypto.createHash("sha256").update(x).digest("hex");
const hashJson=x=>sha256(Buffer.from(JSON.stringify(x)));
const hex64=x=>typeof x==="string"&&/^[a-f0-9]{64}$/.test(x);
const folder=path.resolve(process.argv[2]||"source-output/pair-8098-4626");
const read=n=>fs.readFileSync(path.join(folder,n+".json"));
const graphBytes=read("structural-ast-graph");
const hypothesisBytes=read("generic-source-hypotheses");
const reportBytes=read("source-scientific-report");
const feasibilityBytes=read("path-feasibility");
const graph=JSON.parse(graphBytes),discovery=JSON.parse(hypothesisBytes);
const report=JSON.parse(reportBytes),feasibility=JSON.parse(feasibilityBytes);
assert.equal(graph.schemaVersion,"OECL_SOLIDITY_COMPILER_AST_GRAPH_V1");
assert.equal(discovery.schemaVersion,"OECL_GENERIC_AST_HYPOTHESES_V1");
assert.equal(report.schemaVersion,"OECL_OPEN_GENERIC_AST_RESULT_V1");
assert.equal(report.scientificVerdict,"INCONCLUSIVE");
assert.equal(report.candidateAdmission,"NOT_ADMITTED");
assert.equal(report.sourceOnly,true);
assert.equal(report.evmExecuted,false);
assert.deepEqual(report.selected.map(s=>s.id),["ERC-8098","ERC-4626"]);
assert.equal(discovery.sourceGraphSha256,hashJson(graph));
assert.equal(report.graphSha256,hashJson(graph));
assert.equal(report.hypothesisArtifactSha256,hashJson(discovery));
assert.equal(report.pathFeasibilityArtifactSha256,hashJson(feasibility));
assert.deepEqual(report.hypotheses,discovery.hypotheses);
assert.equal(feasibility.sourceGraphSha256,hashJson(graph));
assert.equal(feasibility.discoverySha256,hashJson(discovery));
assert.equal(discovery.errors.length,0);
const candidates=discovery.hypotheses.filter(h=>h.kind==="POTENTIAL_COUPLED_STATE_DECREASE"&&
 h.status==="SOURCE_ONLY_UNEVALUATED"&&h.scientificVerdict==="INCONCLUSIVE"&&
 h.candidateAdmission==="NOT_ADMITTED"&&Array.isArray(h.evidence)&&h.evidence.length===2);
assert.equal(candidates.length,1,"Cannot arbitrarily choose or invent an AST hypothesis");
const hypothesis=candidates[0];
assert(/^AST-HYP-[a-f0-9]{24}$/.test(hypothesis.hypothesisId));
const sourceSide=report.selected;
const expectedEntrypoints=["burn","redeem"];
const predictions=hypothesis.evidence.map((e,i)=>{
  const source=sourceSide[i];
  assert.equal(e.participant,source.id);
  assert.equal(e.publicEntrypoint?.name,expectedEntrypoints[i],
    "No audited EVM adapter for the actually observed AST entry point");
  assert.equal(e.stateDecrease?.state,"_totalSupply");
  assert(hex64(e.publicEntrypoint.sourceSha256));
  assert(hex64(e.stateDecrease.sourceSha256));
  assert(Array.isArray(e.callPath)&&e.callPath.length>=1&&e.callPath.length<=20);
  const sourceFacts=graph.sources;
  assert(sourceFacts.some(x=>x.sha256===e.stateDecrease.sourceSha256));
  assert(sourceFacts.some(x=>x.sha256===e.publicEntrypoint.sourceSha256));
  return {
    predictionId:sha256(Buffer.from(hypothesis.hypothesisId+"|"+
      source.id+"|"+e.publicEntrypoint.name+"|"+e.stateDecrease.sourceSha256)).slice(0,24),
    parentAstHypothesisId:hypothesis.hypothesisId,
    participant:source.id,
    participantSide:i===0?"A":"B",
    publicEntrypoint:e.publicEntrypoint.name,
    stateVar:e.stateDecrease.state,
    stateSourceSha256:e.stateDecrease.sourceSha256,
    publicEntrypointSourceSha256:e.publicEntrypoint.sourceSha256,
    callPath:e.callPath,
    sourceRevision:source.revision,
    sourceRootSha256:source.sourceSha256,
    implementationRole:i===0?"UNDERLYING_ERC8098":"SEPARATE_ERC4626_SHARES",
    operation:i===0?"BURN_UNDERLYING":"REDEEM_SHARES",
    beforeMetric:i===0?"underlyingSupplyBeforeBurn":"vaultShareSupplyBeforeRedeem",
    afterMetric:i===0?"underlyingSupplyAfterBurn":"vaultShareSupplyAfterRedeem",
    requiredNumericRelation:"STRICTLY_LESS_THAN",
    predictedDirection:"DECREASE",
    falsifier:"A successful owned "+
      e.publicEntrypoint.name+" operation that does not decrease this exact token's totalSupply",
    scientificStatus:"HYPOTHESIS_AST_SOURCE_ONLY"
  };
});
assert.equal(new Set(predictions.map(x=>x.predictionId)).size,2);
const plan={
 schemaVersion:"OECL_AUTOGENERATED_PINNED_AST_HYPOTHESIS_EXPERIMENT_V1",
 experimentId:"OECL-8098-4626-AST-STATE-DECREASE-ROLE-TEST-V1",
 generationMethod:"DETERMINISTIC_AST_FACT_TO_TESTABLE_OPERATION_RULE",
 originatedBy:"OECL_GENERIC_AST_HYPOTHESES_V1",
 originHypothesisId:hypothesis.hypothesisId,
 originHypothesisKind:hypothesis.kind,
 sourceOnlyBeforeExperiment:true,
 preparedBeforeEvmDeployment:true,
 provenance:{
  reportSha256:sha256(reportBytes),
  discoverySha256:sha256(hypothesisBytes),
  graphFileSha256:sha256(graphBytes),
  feasibilitySha256:sha256(feasibilityBytes),
  graphSha256:report.graphSha256,
  compilerVersion:report.compilerVersion,
  dependencyIntegrity:report.dependencyIntegrity,
  sources:report.selected
 },
 predictions,
 plannedSequence:[
  {operation:"REDEEM_SHARES",participant:"ERC-4626",amountTokens:"40"},
  {operation:"BURN_UNDERLYING",participant:"ERC-8098",amountTokens:"10"}
 ],
 admission:"NOT_ADMITTED",
 compatibilityVerdict:"NOT_EVALUATED",
 evmExecuted:false,
 sourceHypothesisStatus:"INCONCLUSIVE",
 limitations:[
  "The AST proposes separate reachable state decreases; it does not establish mutual coupling, executable authorization or atomicity.",
  "A deterministic, fixture-specific reviewed adapter turns observed burn/redeem paths into predictions. This is not open-ended autonomous synthesis or novel economic theory.",
  "No EVM result is read during hypothesis derivation; the source-only plan is SHA-256 pinned before deployment.",
  "Only positive eligible-owner executions are tested; cross-contract interoperability remains NOT_EVALUATED."
 ]
};
const target=path.join(folder,"ast-derived-preregistered-plan.json");
fs.writeFileSync(target,JSON.stringify(plan,null,2)+"\n");
console.log("OECL_AUTOGENERATED_AST_EXPERIMENT_PREREGISTERED",JSON.stringify({
 hypothesisId:plan.originHypothesisId,
 kinds:plan.predictions.map(x=>x.operation),
 pathScreens:feasibility.hypotheses.map(x=>({kind:x.kind,pathScreen:x.pathScreen})),
 planSha256:sha256(fs.readFileSync(target))
}));
