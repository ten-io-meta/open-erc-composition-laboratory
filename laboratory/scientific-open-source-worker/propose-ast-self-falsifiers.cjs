"use strict";
const fs=require("node:fs");
const path=require("node:path");
const crypto=require("node:crypto");
const assert=require("node:assert/strict");
const digest=x=>crypto.createHash("sha256").update(x).digest("hex");
const dir=path.resolve(process.argv[2]||"source-output/pair-8098-4626");
const original=fs.readFileSync(path.join(dir,"ast-derived-preregistered-plan.json"));
const plan=JSON.parse(original);
const report=JSON.parse(fs.readFileSync(path.join(dir,"source-scientific-report.json")));
const discovery=JSON.parse(fs.readFileSync(path.join(dir,"generic-source-hypotheses.json")));
const graph=JSON.parse(fs.readFileSync(path.join(dir,"structural-ast-graph.json")));
const feasibility=JSON.parse(fs.readFileSync(path.join(dir,"path-feasibility.json")));
assert.equal(plan.schemaVersion,"OECL_AUTOGENERATED_PINNED_AST_HYPOTHESIS_EXPERIMENT_V1");
assert.equal(plan.originatedBy,"OECL_GENERIC_AST_HYPOTHESES_V1");
assert.equal(plan.preparedBeforeEvmDeployment,true);
assert.equal(plan.sourceOnlyBeforeExperiment,true);
assert.equal(plan.provenance.reportSha256,digest(fs.readFileSync(path.join(dir,"source-scientific-report.json"))));
assert.equal(discovery.sourceGraphSha256,digest(Buffer.from(JSON.stringify(graph))));
assert.equal(report.graphSha256,discovery.sourceGraphSha256);
assert.equal(feasibility.sourceGraphSha256,discovery.sourceGraphSha256);
assert.equal(plan.provenance.discoverySha256,digest(fs.readFileSync(path.join(dir,"generic-source-hypotheses.json"))));
const sourceHypothesis=discovery.hypotheses.find(x=>
 x.hypothesisId===plan.originHypothesisId&&
 x.kind==="POTENTIAL_COUPLED_STATE_DECREASE");
assert(sourceHypothesis&&sourceHypothesis.evidence?.length===2);
const pathReview=feasibility.hypotheses.find(x=>x.hypothesisId===plan.originHypothesisId);
assert(pathReview&&pathReview.pathScreen==="NOT_PROVEN_EXECUTABLE");
const allowedOperations=new Set(["BURN_UNDERLYING","REDEEM_SHARES"]);
const all=[];
for(const [i,p] of plan.predictions.entries()){
 const evidence=sourceHypothesis.evidence[i];
 assert.equal(evidence.participant,p.participant);
 assert.equal(evidence.publicEntrypoint?.name,p.publicEntrypoint);
 assert.equal(evidence.stateDecrease?.state,"_totalSupply");
 assert.equal(evidence.stateDecrease?.sourceSha256,p.stateSourceSha256);
 assert.deepEqual(evidence.callPath,p.callPath);
 assert(allowedOperations.has(p.operation),"No reviewed local fixture for AST operation");
 assert.equal(p.requiredNumericRelation,"STRICTLY_LESS_THAN");
 // These are SOURCE-GENERATED TEST QUESTIONS. They do not predict results.
 // A success with zero decrease falsifies ONLY the stronger universal claim.
 for(const rule of [
   {kind:"ZERO_AMOUNT_BOUNDARY",
    contestedGeneralization:"EVERY_SUCCESSFUL_CALL_STRICTLY_DECREASES_TOTAL_SUPPLY",
    quantityRule:"ZERO",
    falsificationRule:"SUCCESS_WITH_UNCHANGED_TOTAL_SUPPLY",
    hypothesisStatus:"CHALLENGE_PROPOSED_NOT_EVM_TESTED"},
   {kind:"ABOVE_OWNED_BALANCE",
    contestedGeneralization:"PUBLIC_ENTRYPOINT_ALWAYS_EXECUTABLE",
    quantityRule:"OWNED_TOKEN_BALANCE_PLUS_ONE",
    falsificationRule:"REVERT_WITH_UNCHANGED_STATE",
    hypothesisStatus:"CHALLENGE_PROPOSED_NOT_EVM_TESTED"}
 ]){
  const caseId="AST-COUNTER-"+digest(Buffer.from(
    plan.originHypothesisId+"|"+p.predictionId+"|"+rule.kind)).slice(0,24);
  all.push({caseId,originHypothesisId:plan.originHypothesisId,
    originalScopedPredictionId:p.predictionId,participant:p.participant,
    participantSide:p.participantSide,operation:p.operation,
    entrypoint:p.publicEntrypoint,sourceRevision:p.sourceRevision,
    sourceSha256:p.stateSourceSha256,astCallPath:p.callPath,
    observedStateVar:p.stateVar,quantityRule:rule.quantityRule,
    challengeKind:rule.kind,
    contestedGeneralization:rule.contestedGeneralization,
    falsificationRule:rule.falsificationRule,
    status:rule.hypothesisStatus,
    independentHypothesisStatus:"NOT_ESTABLISHED",
    note:"A boundary counterexample must not be misreported as refuting the original positive-quantity, owner-authorized case."});
 }
}
assert.equal(all.length,4);
assert.equal(new Set(all.map(x=>x.caseId)).size,4);
const artifact={
 schemaVersion:"OECL_AST_SELF_FALSIFICATION_PLAN_V1",
 experimentId:plan.experimentId,
 originHypothesisId:plan.originHypothesisId,
 originatingSourceKind:plan.originHypothesisKind,
 generationMethod:"RULE_BASED_BOUNDARY_CHALLENGE_FROM_COMPILER_AST",
 generatedBeforeEvmDeployment:true,
 emulatedEvmOrReceipt:false,
 sourcePlanSha256:digest(original),
 sourceGraphSha256:report.graphSha256,
 graphRevisionScope:"IMMUTABLE_COMPILER_SOURCE_UNITS",
 selected:report.selected,
 sourcePathScreen:pathReview.pathScreen,
 originalScopedHypothesis:"SOURCE_ONLY_PATH_TO_STATE_DECREASE_UNDER_UNRESOLVED_CONDITIONS",
 challenges:all,
 scientificVerdict:"INCONCLUSIVE",
 compatibilityVerdict:"NOT_EVALUATED",
 candidateAdmission:"NOT_ADMITTED",
 limitations:[
  "Challenges test potential overgeneralizations of an AST hypothesis, not the strictly scoped original positive experiment.",
  "Zero and balance+1 boundary rules are generated by a deterministic reviewed planner for supported token methods, not free-form autonomous research.",
  "A reverted operation is a negative EVM path, never evidence that a successfully executed path did not decrease supply.",
  "No claim of automatic detection of financial vulnerabilities, permission bypass or atomic coupling."
 ]
};
const file=path.join(dir,"ast-self-falsification-plan.json");
fs.writeFileSync(file,JSON.stringify(artifact,null,2)+"\n");
console.log("OECL_AST_SELF_FALSIFICATION_PLAN_REGISTERED",JSON.stringify({
 originHypothesisId:artifact.originHypothesisId,
 challenges:all.map(x=>x.operation+":"+x.challengeKind),
 planSha256:digest(fs.readFileSync(file)),
 previousPlanSha256:artifact.sourcePlanSha256
}));
