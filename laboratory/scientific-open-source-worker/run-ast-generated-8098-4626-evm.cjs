"use strict";
const fs=require("node:fs");
const path=require("node:path");
const crypto=require("node:crypto");
const assert=require("node:assert/strict");
const sha256=x=>crypto.createHash("sha256").update(x).digest("hex");
const hex40=x=>typeof x==="string"&&/^[a-f0-9]{40}$/i.test(x);
const hex64=x=>typeof x==="string"&&/^[a-f0-9]{64}$/i.test(x);
const hexTx=x=>typeof x==="string"&&/^0x[a-f0-9]{64}$/i.test(x);
const anchor=["AST-HYP-7bb4f7ca6a8dfee4feeb62cc","POTENTIAL_COUPLED_STATE_DECREASE"];
/**
 * Lock a dynamically generated hypothesis and test plan BEFORE deploying
 * contracts. No artifact with an EVM result is read in this step.
 */
function readAstDerivedPlan(folder){
  const filename=path.join(folder,"ast-derived-preregistered-plan.json");
  const bytes=fs.readFileSync(filename);
  const plan=JSON.parse(bytes.toString("utf8"));
  assert.equal(plan.schemaVersion,
    "OECL_AUTOGENERATED_PINNED_AST_HYPOTHESIS_EXPERIMENT_V1");
  assert.equal(plan.originatedBy,"OECL_GENERIC_AST_HYPOTHESES_V1");
  assert.equal(plan.generationMethod,
    "DETERMINISTIC_AST_FACT_TO_TESTABLE_OPERATION_RULE");
  // The ID is not hardcoded into the candidate generator; the experiment
  // captures what the real compiler AST discovered on this pinned revision.
  assert(/^AST-HYP-[a-f0-9]{24}$/.test(plan.originHypothesisId));
  assert.equal(plan.originHypothesisKind,anchor[1]);
  assert.equal(plan.sourceOnlyBeforeExperiment,true);
  assert.equal(plan.preparedBeforeEvmDeployment,true);
  assert.equal(plan.evmExecuted,false);
  assert.equal(plan.admission,"NOT_ADMITTED");
  assert.equal(plan.compatibilityVerdict,"NOT_EVALUATED");
  assert.equal(plan.predictions?.length,2);
  assert.deepEqual(plan.predictions.map(p=>p.operation),
    ["BURN_UNDERLYING","REDEEM_SHARES"]);
  assert(plan.predictions.every(p=>p.parentAstHypothesisId===
    plan.originHypothesisId&&p.predictedDirection==="DECREASE"&&
    p.requiredNumericRelation==="STRICTLY_LESS_THAN"&&
    p.stateVar==="_totalSupply"&&hex64(p.stateSourceSha256)&&
    hex64(p.sourceRootSha256)&&Array.isArray(p.callPath)&&p.callPath.length>0));
  const sourceReportBytes=fs.readFileSync(path.join(folder,"source-scientific-report.json"));
  const sourceReport=JSON.parse(sourceReportBytes);
  assert.equal(sha256(sourceReportBytes),plan.provenance.reportSha256);
  assert.equal(sourceReport.graphSha256,plan.provenance.graphSha256);
  assert.deepEqual(sourceReport.selected,plan.provenance.sources);
  const hypothesisBytes=fs.readFileSync(path.join(folder,"generic-source-hypotheses.json"));
  const hypothesis=JSON.parse(hypothesisBytes);
  assert.equal(sha256(hypothesisBytes),plan.provenance.discoverySha256);
  assert(hypothesis.hypotheses.some(h=>h.hypothesisId===plan.originHypothesisId &&
    h.kind===plan.originHypothesisKind));
  assert.equal(sourceReport.scientificVerdict,"INCONCLUSIVE");
  assert.equal(sourceReport.sourceOnly,true);
  return {plan,planSha256:sha256(bytes),filename,folder};
}
async function checkTx({provider,ethers,receipt,contract,expectedSender,
  method,expectedAmount,expectedBurnEvent}){
  assert(receipt?.status===1 && hexTx(receipt.transactionHash));
  const actual=await provider.getTransactionReceipt(receipt.transactionHash);
  assert(actual&&actual.status===1);
  assert.equal(actual.transactionHash,receipt.transactionHash);
  assert.equal(actual.blockHash,receipt.blockHash);
  assert.equal(actual.blockNumber,receipt.blockNumber);
  const block=await provider.getBlock(actual.blockNumber);
  assert(block&&block.hash===actual.blockHash&&
    block.transactions.includes(actual.transactionHash));
  const tx=await provider.getTransaction(actual.transactionHash);
  assert(tx&&tx.to.toLowerCase()===contract.address.toLowerCase());
  assert.equal(tx.from.toLowerCase(),expectedSender.toLowerCase());
  assert.equal(tx.data.slice(0,10).toLowerCase(),
    contract.interface.getSighash(method).toLowerCase());
  const parsed=contract.interface.decodeFunctionData(method,tx.data);
  assert.equal(parsed[0].toString(),expectedAmount.toString());
  const topic=contract.interface.getEventTopic("Transfer");
  const burns=actual.logs.filter(l=>l.address.toLowerCase()===
    contract.address.toLowerCase()&&l.topics[0]?.toLowerCase()===topic.toLowerCase())
    .map(l=>contract.interface.parseLog(l))
    .filter(e=>e.args.from.toLowerCase()===expectedSender.toLowerCase() &&
      e.args.to.toLowerCase()===ethers.constants.AddressZero.toLowerCase() &&
      e.args.value.eq(expectedAmount));
  assert.equal(burns.length,1,"Expected one ERC20 Transfer-to-zero burn");
  const code=await provider.getCode(contract.address,actual.blockNumber);
  assert(code&&code!=="0x");
  return {
    transactionHash:actual.transactionHash,blockHash:actual.blockHash,
    blockNumber:actual.blockNumber,gasUsed:actual.gasUsed.toString(),
    status:actual.status,to:tx.to,from:tx.from,
    methodSelector:tx.data.slice(0,10),
    deployedCodeHash:ethers.utils.keccak256(code),
    verifiedBurnEvent:{name:"Transfer",burnAmount:expectedAmount.toString(),
      tokenAddress:contract.address,from:expectedSender,
      to:ethers.constants.AddressZero,burnLogCount:burns.length},
    proofScope:"LOCAL_HARDHAT_PROVIDER_RECEIPT_AND_BLOCK_VERIFIED"
  };
}
async function checkSourceGeneratedHypothesis(x){
  const {registration,provider,ethers,asset,vault,owner,
    afterDeposit,afterRedeem,final,redeemReceipt,burnReceipt,
    redeemAmount,burnAmount,sourceRevision,sourceRootSha256,
    vaultSourceRootSha256,vaultWrapperSha256,compilerVersion,
    dependencyIntegrity,openzeppelinVersion,output}=x;
  const {plan,planSha256,filename}=registration;
  assert.equal(plan.provenance.sources[0].revision,sourceRevision);
  assert.equal(plan.provenance.sources[0].sourceSha256,sourceRootSha256);
  assert.equal(plan.provenance.sources[1].sourceSha256,vaultSourceRootSha256);
  assert.equal(plan.provenance.sources[1].revision,openzeppelinVersion);
  assert.equal(plan.provenance.compilerVersion,compilerVersion);
  assert.equal(plan.provenance.dependencyIntegrity,dependencyIntegrity);
  assert.equal(plan.plannedSequence[0].amountTokens,ethers.utils.formatUnits(redeemAmount,18));
  assert.equal(plan.plannedSequence[1].amountTokens,ethers.utils.formatUnits(burnAmount,18));
  const network=await provider.getNetwork();
  assert.equal(Number(network.chainId),31337);
  const witnesses={
    REDEEM_SHARES:await checkTx({provider,ethers,receipt:redeemReceipt,
      contract:vault,expectedSender:owner.address,
      method:"redeem(uint256,address,address)",
      expectedAmount:redeemAmount}),
    BURN_UNDERLYING:await checkTx({provider,ethers,receipt:burnReceipt,
      contract:asset,expectedSender:owner.address,
      method:"burn(uint256)",expectedAmount:burnAmount})
  };
  const metrics={
    underlyingSupplyBeforeBurn:afterRedeem.underlyingSupply,
    underlyingSupplyAfterBurn:final.underlyingSupply,
    vaultShareSupplyBeforeRedeem:afterDeposit.vaultShareSupply,
    vaultShareSupplyAfterRedeem:afterRedeem.vaultShareSupply
  };
  const observations=plan.predictions.map(p=>{
    const before=BigInt(metrics[p.beforeMetric]);
    const after=BigInt(metrics[p.afterMetric]);
    const hasDecrease=after<before;
    const role=p.operation==="BURN_UNDERLYING"?"A":"B";
    assert.equal(p.participantSide,role);
    const sourceRevisionForRole=role==="A"?
      sourceRevision:"sha256:"+vaultSourceRootSha256;
    // A fixture-specific adapter chooses an operation and role AFTER
    // an AST hypothesis is generated, not a forged generic interoperability result.
    return {
      parentAstHypothesisId:p.parentAstHypothesisId,
      predictionId:p.predictionId,
      experimentalOperation:p.operation,
      sourceEntrypoint:p.publicEntrypoint,
      graphCallPath:p.callPath,
      finding:"ACTUAL_LOCAL_OWNED_OPERATION_STATE_DECREASE",
      strictNumericRelationHolds:hasDecrease,
      outcome:hasDecrease?
        "SCOPED_HYPOTHESIS_SUPPORTED_BY_OBSERVATION":
        "SCOPED_HYPOTHESIS_CHALLENGED_BY_OBSERVATION",
      before:before.toString(),after:after.toString(),
      witness:witnesses[p.operation],
      prediction:{
        hypothesisId:p.predictionId,
        candidateId:plan.experimentId,
        constraintId:"AST-CONSTRAINT-"+p.predictionId,
        participantSide:p.participantSide,
        sourceRevision:sourceRevisionForRole,
        scenarioId:plan.experimentId+"::"+p.operation,
        expectedConstraintVerdict:"PRESERVED"
      },
      constraint:{
        constraintId:"AST-CONSTRAINT-"+p.predictionId,
        candidateId:plan.experimentId,participantSide:p.participantSide,
        participantKind:"PROTOCOL",participantId:p.participant,
        sourceId:"PINNED-AST-"+p.participant,
        sourceRevision:sourceRevisionForRole,
        factId:"AST-SOURCE-DECREASE-"+p.predictionId,
        basis:"SOURCE_DERIVED_BEHAVIORAL_INVARIANT",
        containerKind:"CONTRACT",
        containerSymbol:role==="A"?"ERC8098Reference":"OECL8098AssetVault",
        locator:{sourceLocation:role==="A"?
          "PINNED_GITHUB_SOURCE":"PINNED_OZ4_9_6_SOURCE"},
        rawText:"Source generated path to "+p.stateVar+" decrease in "+p.publicEntrypoint,
        behavioralPredicate:{
          kind:"UNSIGNED_INTEGER_RELATION",
          operator:"LTE",leftMetric:p.afterMetric,rightMetric:p.beforeMetric
        }
      },
      observation:{
        observationId:"AST-OBS-"+p.predictionId,
        candidateId:plan.experimentId,
        constraintId:"AST-CONSTRAINT-"+p.predictionId,
        participantSide:p.participantSide,
        verdict:after<=before?"PRESERVED":"VIOLATED",
        evidence:["LOCAL_BLOCKED_TX_WITNESS","MINED_EVENT_TRANSFER_TO_ZERO",
          "SOURCE_DERIVED_HYPOTHESIS_PREREGISTRATION"],
        numericMeasurements:{
          [p.beforeMetric]:before.toString(),
          [p.afterMetric]:after.toString()
        },
        sourceRevision:sourceRevisionForRole,
        transactionHash:witnesses[p.operation].transactionHash
      }
    };
  });
  const crossChecks={
    underlyingSupplyUnaffectedByRedeem:
      afterDeposit.underlyingSupply===afterRedeem.underlyingSupply,
    sharesSupplyUnaffectedByIndependentAssetBurn:
      afterRedeem.vaultShareSupply===final.vaultShareSupply
  };
  const result={
    schemaVersion:"OECL_AST_GENERATED_HYPOTHESIS_EVM_OBSERVATION_V1",
    planSha256,
    originHypothesisId:plan.originHypothesisId,
    originHypothesisKind:plan.originHypothesisKind,
    evidenceScope:"SOURCE_AST_PLAN_THEN_PINNED_LOCAL_EVM",
    planRegisteredBeforeDeployment:true,
    localChainId:31337,
    sourceGraphSha256:plan.provenance.graphSha256,
    compilerVersion,dependencyIntegrity,
    actualRootSourceDigests:{underlying:sourceRootSha256,
      vaultOZRoot:vaultSourceRootSha256,vaultWrapper:vaultWrapperSha256},
    metrics,observations,crossChecks,
    sourceScientificVerdict:"INCONCLUSIVE",
    candidateAdmission:"NOT_ADMITTED",
    fullCompatibilityVerdict:"NOT_EVALUATED",
    limitations:[
      "The prediction is mechanically derived from one compiler AST state-decrease hypothesis and a reviewed fixture-specific operation adapter.",
      "AST path feasibility was not proved before local EVM execution; the experiment supplies only these two observed owner-authorized cases.",
      "A decrease after two independent transactions does not prove a coupled or atomic composition pathway.",
      "Signed independently by no Ethereum consensus authority. Local Hardhat provider witness only; no Ethereum mainnet observation."
    ]
  };
  assert.equal(observations.length,2);
  assert(observations.every(o=>o.strictNumericRelationHolds===true));
  assert(crossChecks.underlyingSupplyUnaffectedByRedeem);
  assert(crossChecks.sharesSupplyUnaffectedByIndependentAssetBurn);
  assert.equal(sha256(fs.readFileSync(filename)),planSha256,
    "Source-derived plan changed after EVM deployment");
  fs.writeFileSync(path.join(output,"ast-hypothesis-experiment.json"),
    JSON.stringify(result,null,2)+"\n");
  console.log("OECL_AST_GENERATED_HYPOTHESIS_LOCAL_EVM_PASS",JSON.stringify({
    parentHypothesisId:plan.originHypothesisId,
    sourceDerivedPredictions:observations.length,
    observedDecreases:observations.filter(o=>o.strictNumericRelationHolds).length,
    receipts:observations.map(o=>o.witness.transactionHash),
    scope:result.evidenceScope,verdict:result.fullCompatibilityVerdict
  }));
  return result;
}
module.exports={readAstDerivedPlan,checkSourceGeneratedHypothesis};
