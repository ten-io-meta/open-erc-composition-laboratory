 function decode(receipt,asset,vault){
  const events=[];
  for(const log of receipt.logs){
   const type=log.address.toLowerCase()===asset.address.toLowerCase()?"ASSET":
    log.address.toLowerCase()===vault.address.toLowerCase()?"VAULT":null;
   if(!type)throw Error("UNREVIEWED_EVENT_EMITTER");
   const {name,args}=((type==="ASSET"?asset:vault).interface.parseLog(log));
   if(["Transfer","Approval"].includes(name)){
    events.push({contract:type,name,from:args[0],to:args[1],amount:args[2].toString()});
   }else if(name==="Deposit"){
    events.push({contract:"VAULT",name,sender:args[0],receiver:args[1],
     assets:args[2].toString(),shares:args[3].toString()});
   }else if(name==="Withdraw"){
    events.push({contract:"VAULT",name,sender:args[0],receiver:args[1],
     owner:args[2],assets:args[3].toString(),shares:args[4].toString()});
   }else throw Error("UNREVIEWED_EVENT_NAME");
  }
  return events;
 }
 async function checked(tx,target,method,asset,vault){
  const rc=await tx.wait(1),onChain=await provider.getTransactionReceipt(tx.hash),
   info=await provider.getTransaction(tx.hash),block=await provider.getBlock(rc.blockNumber);
  assert(rc&&onChain&&info&&block&&block.transactions);
  assert.equal(rc.status,1);assert.equal(onChain.status,1);
  assert.equal(rc.blockHash,onChain.blockHash);assert.equal(rc.blockHash,block.hash);
  assert(block.transactions.some(x=>x.toLowerCase()===tx.hash.toLowerCase()));
  assert.equal(info.from.toLowerCase(),owner.address.toLowerCase());
  assert.equal(info.to?.toLowerCase()||null,target?.address.toLowerCase()||null);
  assert(rc.gasUsed.gt(0)&&rc.gasUsed.lte(NUMERIC_POLICY.maxGasPerTx));
  assert(rc.blockNumber>lastBlock);
  lastBlock=rc.blockNumber;count++;
  if(target)assert.equal(info.data.slice(0,10),target.interface.getSighash(method));
  return {txHash:tx.hash,blockHash:rc.blockHash,blockNumber:rc.blockNumber,
   status:1,transactionMined:true,method,
   from:info.from,to:info.to,
   methodSelector:target?info.data.slice(0,10):"CREATE",gasUsed:rc.gasUsed.toString(),
   events:target?decode(rc,asset,vault):[]};
 }
 function expectedEvents(step,actor,vault,amount,shares){
  const transfer=(contract,from,to,value)=>({contract,name:"Transfer",from,to,amount:value});
  const approval=value=>({contract:"ASSET",name:"Approval",from:actor,to:vault,amount:value});
  if(step==="MINT_TEST_ASSET")return [transfer("ASSET",ZERO,actor,amount)];
  if(step==="APPROVE_VAULT_ASSETS")return [approval(amount)];
  if(step==="DEPOSIT_UNDERLYING")return [
   approval("0"),transfer("ASSET",actor,vault,amount),
   transfer("VAULT",ZERO,actor,shares),
   {contract:"VAULT",name:"Deposit",sender:actor,receiver:actor,assets:amount,shares}];
  if(step==="DIRECT_UNDERLYING_DONATION")return [transfer("ASSET",actor,vault,amount)];
  if(step==="WITHDRAW_TEST")return [
   transfer("VAULT",actor,ZERO,shares),transfer("ASSET",vault,actor,amount),
   {contract:"VAULT",name:"Withdraw",sender:actor,receiver:actor,owner:actor,
    assets:amount,shares}];
  throw Error("UNREVIEWED_EXPECTED_TYPED_EVENT_STEP");
 }
