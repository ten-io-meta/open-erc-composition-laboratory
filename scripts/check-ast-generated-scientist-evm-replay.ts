import assert from "node:assert/strict";
import {createHash} from "node:crypto";
import {createRequire} from "node:module";
import {readFileSync,mkdirSync,writeFileSync} from "node:fs";
import {resolve,dirname} from "node:path";
import {ScientificEvmHypothesisAlignmentEngine} from
    "../laboratory/scientific-independent-review/ScientificEvmHypothesisAlignmentEngine.js";
import type {ScopedScientificPrediction} from
    "../laboratory/scientific-independent-review/ScientificEvmHypothesisAlignmentEngine.js";
import type {ScientificCompositionConstraint} from
    "../laboratory/scientific-composition-evaluation-specification/ScientificCompositionConstraint.js";
import type {ScientificCompositionConstraintObservation} from
    "../laboratory/scientific-composition-constraint-evaluation/ScientificCompositionConstraintObservation.js";

const require=createRequire(import.meta.url);
const {discoverGenericPair}=require(
    "../laboratory/scientific-open-source-worker/GenericAstPairHypotheses.cjs");
const registry=require("../laboratory/scientific-open-source-worker/source-registry.json");
const folder=resolve(process.argv[2]||"source-output/pair-8098-4626");
const output=resolve(process.argv[3]||"audit-output/scientist-ast-generated-evm-review.json");
const read=(name:string)=>readFileSync(resolve(folder,name+".json"));
const sha256=(bytes:Uint8Array)=>createHash("sha256").update(bytes).digest("hex");
const jsonHash=(obj:unknown)=>sha256(Buffer.from(JSON.stringify(obj)));
const graphBytes=read("structural-ast-graph");
const hypothesisBytes=read("generic-source-hypotheses");
const reportBytes=read("source-scientific-report");
const planBytes=read("ast-derived-preregistered-plan");
const evmBytes=read("ast-hypothesis-experiment");
const graph=JSON.parse(graphBytes.toString("utf8"));
const discovery=JSON.parse(hypothesisBytes.toString("utf8"));
const sourceReport=JSON.parse(reportBytes.toString("utf8"));
const plan=JSON.parse(planBytes.toString("utf8"));
const evm=JSON.parse(evmBytes.toString("utf8"));
const old=JSON.parse(read("independent-8098-underlying-4626-evm").toString("utf8"));
assert.equal(plan.schemaVersion,"OECL_AUTOGENERATED_PINNED_AST_HYPOTHESIS_EXPERIMENT_V1");
assert.equal(plan.preparedBeforeEvmDeployment,true);
assert.equal(plan.sourceOnlyBeforeExperiment,true);
assert.equal(plan.evmExecuted,false);
assert.equal(plan.originatedBy,"OECL_GENERIC_AST_HYPOTHESES_V1");
assert.equal(plan.generationMethod,"DETERMINISTIC_AST_FACT_TO_TESTABLE_OPERATION_RULE");
assert.equal(plan.provenance.graphSha256,jsonHash(graph));
assert.equal(plan.provenance.discoverySha256,sha256(hypothesisBytes));
assert.equal(plan.provenance.reportSha256,sha256(reportBytes));
assert.equal(sourceReport.graphSha256,plan.provenance.graphSha256);
assert.equal(sourceReport.hypothesisArtifactSha256,jsonHash(discovery));
assert.equal(plan.originHypothesisKind,"POTENTIAL_COUPLED_STATE_DECREASE");
const selected=sourceReport.selected;
assert.deepEqual(selected.map((s:any)=>s.id),["ERC-8098","ERC-4626"]);
assert.deepEqual(plan.provenance.sources,selected);
const primary=selected.map((s:any)=>({
    id:s.id,unit:s.sourceUnit,
    contract:registry.sources.find((x:any)=>x.id===s.id).contract
}));
const rerun=discoverGenericPair(graph,primary);
assert.deepEqual(rerun,discovery,
    "Regenerated original AST facts disagree with archived source discovery");
const derived=rerun.hypotheses.filter((h:any)=>
    h.kind===plan.originHypothesisKind&&
    h.hypothesisId===plan.originHypothesisId);
assert.equal(derived.length,1,"The experimental hypothesis is not from the compiler AST");
assert.equal(evm.schemaVersion,"OECL_AST_GENERATED_HYPOTHESIS_EVM_OBSERVATION_V1");
assert.equal(evm.originHypothesisId,derived[0].hypothesisId);
assert.equal(evm.originHypothesisKind,derived[0].kind);
assert.equal(evm.planSha256,sha256(planBytes));
assert.equal(evm.planRegisteredBeforeDeployment,true);
assert.equal(evm.sourceGraphSha256,jsonHash(graph));
assert.equal(evm.localChainId,31337);
assert.equal(evm.fullCompatibilityVerdict,"NOT_EVALUATED");
assert.equal(evm.candidateAdmission,"NOT_ADMITTED");
assert.equal(evm.sourceScientificVerdict,"INCONCLUSIVE");
assert.equal(evm.compilerVersion,sourceReport.compilerVersion);
assert.equal(evm.dependencyIntegrity,sourceReport.dependencyIntegrity);
assert.equal(evm.actualRootSourceDigests.underlying,selected[0].sourceSha256);
assert.equal(evm.actualRootSourceDigests.vaultOZRoot,selected[1].sourceSha256);
assert.equal(evm.actualRootSourceDigests.vaultWrapper,old.provenance.vaultWrapperSha256);
assert.equal(evm.observations.length,2);
assert.deepEqual(plan.predictions.map((p:any)=>p.operation),
    ["BURN_UNDERLYING","REDEEM_SHARES"]);
assert.equal(evm.crossChecks.underlyingSupplyUnaffectedByRedeem,true);
assert.equal(evm.crossChecks.sharesSupplyUnaffectedByIndependentAssetBurn,true);
assert.equal(evm.metrics.underlyingSupplyBeforeBurn,old.observations.afterRedeem.underlyingSupply);
assert.equal(evm.metrics.underlyingSupplyAfterBurn,old.observations.final.underlyingSupply);
assert.equal(evm.metrics.vaultShareSupplyBeforeRedeem,old.observations.afterDeposit.vaultShareSupply);
assert.equal(evm.metrics.vaultShareSupplyAfterRedeem,old.observations.afterRedeem.vaultShareSupply);
const engine=new ScientificEvmHypothesisAlignmentEngine();
const checked=[];
for(let i=0;i<2;i++){
    const p=plan.predictions[i],r=evm.observations[i];
    assert.equal(p.parentAstHypothesisId,plan.originHypothesisId);
    assert.equal(r.parentAstHypothesisId,plan.originHypothesisId);
    assert.equal(r.predictionId,p.predictionId);
    assert.equal(r.experimentalOperation,p.operation);
    assert.equal(r.sourceEntrypoint,p.publicEntrypoint);
    assert.deepEqual(r.graphCallPath,p.callPath);
    assert.equal(r.observation.evidence.length,3);
    assert.equal(r.observation.transactionHash,r.witness.transactionHash);
    assert.equal(r.observation.constraintId,r.prediction.constraintId);
    assert.equal(r.observation.sourceRevision,r.prediction.sourceRevision);
    assert.equal(r.constraint.sourceRevision,r.prediction.sourceRevision);
    assert.equal(r.prediction.participantSide,p.participantSide);
    assert.equal(r.constraint.behavioralPredicate.leftMetric,p.afterMetric);
    assert.equal(r.constraint.behavioralPredicate.rightMetric,p.beforeMetric);
    assert.equal(r.constraint.behavioralPredicate.operator,"LTE");
    assert.equal(r.witness.status,1);
    assert.equal(r.witness.proofScope,"LOCAL_HARDHAT_PROVIDER_RECEIPT_AND_BLOCK_VERIFIED");
    assert.match(r.witness.deployedCodeHash,/^0x[a-f0-9]{64}$/i);
    const matching=old.minedReceipts.filter((receipt:any)=>
        receipt.txHash===r.witness.transactionHash);
    assert.equal(matching.length,1);
    assert.equal(matching[0].blockNumber,r.witness.blockNumber);
    const before=BigInt(evm.metrics[p.beforeMetric]);
    const after=BigInt(evm.metrics[p.afterMetric]);
    assert(before>after,"Source AST path did not produce the expected strict decrease");
    assert.equal(r.strictNumericRelationHolds,true);
    assert.equal(r.before,before.toString());
    assert.equal(r.after,after.toString());
    assert.equal(r.observation.numericMeasurements[p.afterMetric],after.toString());
    assert.equal(r.observation.numericMeasurements[p.beforeMetric],before.toString());
    const comparison=engine.compare(r.prediction as ScopedScientificPrediction,
        r.constraint as ScientificCompositionConstraint,
        r.observation as ScientificCompositionConstraintObservation,
        r.prediction.scenarioId);
    assert.equal(comparison.status,"REPORTED_MEASUREMENTS_MATCH_PREDICTION");
    assert.equal(comparison.receiptAuthentication,"NOT_PERFORMED_BY_COMPARISON_ENGINE");
    assert.equal(comparison.fullCompatibilityVerdict,"NOT_EVALUATED");
    assert.equal(comparison.candidateAdmission,"NOT_ADMITTED");
    assert.equal(engine.compare({...r.prediction,sourceRevision:"f".repeat(40)},
        r.constraint,r.observation,r.prediction.scenarioId).status,"NOT_COMPARABLE");
    assert.equal(engine.compare(r.prediction,r.constraint,
        {...r.observation,transactionHash:undefined},
        r.prediction.scenarioId).status,"NOT_COMPARABLE");
    assert.equal(engine.compare(r.prediction,r.constraint,
        {...r.observation,verdict:"VIOLATED"},
        r.prediction.scenarioId).status,"NOT_COMPARABLE");
    const asSource=derived[0].evidence[i];
    assert.equal(asSource.publicEntrypoint.name,p.publicEntrypoint);
    assert.equal(asSource.stateDecrease.state,p.stateVar);
    assert.equal(asSource.publicEntrypoint.sourceSha256,p.publicEntrypointSourceSha256);
    assert.equal(asSource.stateDecrease.sourceSha256,p.stateSourceSha256);
    checked.push({
        hypothesisId:plan.originHypothesisId,
        predictionId:p.predictionId,sourceEntrypoint:p.publicEntrypoint,
        sourcePathOrigin:"COMPILER_AST_AND_PINNED_SOURCE_SHA256",
        executableRole:p.implementationRole,
        predicted:"STRICTLY_DECREASING_STATE",
        measured:{before:r.before,after:r.after},
        result:"SUPPORTED_ON_THIS_EXACT_POSITIVE_EVM_ROUTE",
        minedReceipt:r.witness.transactionHash,
        localProviderVerified:true,
        hypothesisEvmComparator:comparison.status,
        scientificCompatibilityVerdict:"NOT_EVALUATED"
    });
}
assert.equal(checked.length,2);
const review={
    schemaVersion:"OECL_AST_GENERATED_EXPERIMENT_INDEPENDENT_REPLAY_V1",
    sourceHypothesisId:plan.originHypothesisId,
    preregistrationSha256:sha256(planBytes),
    sourceGraphSha256:jsonHash(graph),
    sourceGeneratedEvmArtifactSha256:sha256(evmBytes),
    scope:"AST_DISCOVERED_PATHS_TESTED_IN_FIXED_POSITIVE_LOCAL_EVM_FIXTURE",
    outcomes:checked,
    autonomousDiscoveryScope:"DETERMINISTIC_AST_CANDIDATE_DISCOVERY_WITH_HUMAN_REVIEWED_EVM_ADAPTER",
    independentlyReplayed:true,
    receiptScope:"LIVE_LOCAL_PROVIDER_CHECKED_UPSTREAM_NOT_ETHEREUM_CONSENSUS_ATTESTED",
    scientificVerdict:"INCONCLUSIVE",
    universalCompatibilityVerdict:"NOT_EVALUATED",
    candidateAdmission:"NOT_ADMITTED",
    knownLimitations:[
      "The AST predicted possible decreases but did not establish unconditionally executable paths.",
      "Positive paths do not prove joint atomic execution, full interoperability or a universal guarantee.",
      "Local EVM receipt checking occurred upstream; this job rechecks artifacts and numerical predicates but not Ethereum mainnet consensus.",
      "This is rule-based source-hypothesis generation plus a fixed experimental adapter, not unbounded autonomous scientific theory generation."
    ]
};
mkdirSync(dirname(output),{recursive:true});
writeFileSync(output,JSON.stringify(review,null,2)+"\n");
console.log("OECL_AST_GENERATED_SCIENTIST_INDEPENDENT_EVM_REPLAY_PASS",
    JSON.stringify({hypothesis:plan.originHypothesisId,
      sourcePathsTested:checked.length,positiveObservations:checked.length,
      sourceGraphSha256:review.sourceGraphSha256,
      verdict:review.universalCompatibilityVerdict}));
