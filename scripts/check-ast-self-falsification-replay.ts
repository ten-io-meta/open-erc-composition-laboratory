import assert from "node:assert/strict";
import {createHash} from "node:crypto";
import {readFileSync,writeFileSync,mkdirSync} from "node:fs";
import {resolve,dirname} from "node:path";

const folder=resolve(process.argv[2]||"source-output/pair-8098-4626");
const destination=resolve(process.argv[3]||"audit-output/scientist-ast-self-falsification-review.json");
const read=(name:string)=>readFileSync(resolve(folder,name+".json"));
const parse=(name:string)=>JSON.parse(read(name).toString("utf8"));
const hash=(x:Uint8Array)=>createHash("sha256").update(x).digest("hex");
const originalPlanBytes=read("ast-derived-preregistered-plan");
const challengedPlanBytes=read("ast-self-falsification-plan");
const experimentBytes=read("ast-self-falsification-evm");
const sourceBytes=read("source-scientific-report");
const originalPlan=JSON.parse(originalPlanBytes.toString("utf8"));
const plan=JSON.parse(challengedPlanBytes.toString("utf8"));
const evm=JSON.parse(experimentBytes.toString("utf8"));
const source=JSON.parse(sourceBytes.toString("utf8"));
const positive=parse("ast-hypothesis-experiment");
const originalEvm=parse("independent-8098-underlying-4626-evm");
assert.equal(plan.schemaVersion,"OECL_AST_SELF_FALSIFICATION_PLAN_V1");
assert.equal(plan.sourcePlanSha256,hash(originalPlanBytes));
assert.equal(plan.sourceGraphSha256,source.graphSha256);
assert.equal(plan.originHypothesisId,originalPlan.originHypothesisId);
assert.equal(plan.generatedBeforeEvmDeployment,true);
assert.equal(plan.emulatedEvmOrReceipt,false);
assert.equal(plan.generationMethod,"RULE_BASED_BOUNDARY_CHALLENGE_FROM_COMPILER_AST");
assert.equal(plan.compatibilityVerdict,"NOT_EVALUATED");
assert.equal(source.candidateAdmission,"NOT_ADMITTED");
assert.equal(source.evmExecuted,false);
assert.equal(evm.schemaVersion,"OECL_AST_AUTOGENERATED_COUNTEREXAMPLES_LOCAL_EVM_V1");
assert.equal(evm.counterfactualPlanSha256,hash(challengedPlanBytes));
assert.equal(evm.originalPositivePlanSha256,hash(originalPlanBytes));
assert.equal(evm.originHypothesisId,originalPlan.originHypothesisId);
assert.equal(evm.generatedBeforeEvmDeployment,true);
assert.equal(evm.compatibilityVerdict,"NOT_EVALUATED");
assert.equal(evm.candidateAdmission,"NOT_ADMITTED");
assert.equal(evm.localChainId,31337);
assert.equal(evm.cases.length,4);
assert.equal(plan.challenges.length,4);
assert.equal(positive.sourceScientificVerdict,"INCONCLUSIVE");
assert.equal(positive.originHypothesisId,plan.originHypothesisId);
assert.equal(positive.observations.length,2);
assert(positive.observations.every((x:any)=>x.strictNumericRelationHolds===true));
assert.equal(evm.baselineStateAfterDeposit.underlyingSupply,
    originalEvm.observations.afterDeposit.underlyingSupply);
assert.equal(evm.baselineStateAfterDeposit.vaultShareSupply,
    originalEvm.observations.afterDeposit.vaultShareSupply);
assert.equal(evm.cases.filter((x:any)=>x.challengeKind==="ZERO_AMOUNT_BOUNDARY").length,2);
assert.equal(evm.cases.filter((x:any)=>x.challengeKind==="ABOVE_OWNED_BALANCE").length,2);
const checked=[];
for(let i=0;i<plan.challenges.length;i++){
    const predicted=plan.challenges[i],caseResult=evm.cases[i];
    assert.equal(caseResult.caseId,predicted.caseId);
    assert.equal(caseResult.originHypothesisId,predicted.originHypothesisId);
    assert.equal(caseResult.originalScopedPredictionId,predicted.originalScopedPredictionId);
    assert.equal(caseResult.challengeKind,predicted.challengeKind);
    assert.equal(caseResult.operation,predicted.operation);
    assert.equal(caseResult.sourceSha256,predicted.sourceSha256);
    assert.equal(caseResult.sourceRevision,predicted.sourceRevision);
    assert.equal(caseResult.contestedGeneralization,predicted.contestedGeneralization);
    assert.equal(caseResult.falsificationRule,predicted.falsificationRule);
    assert.equal(caseResult.generalCompatibilityVerdict,"NOT_EVALUATED");
    assert.equal(caseResult.candidateAdmission,"NOT_ADMITTED");
    assert.equal(caseResult.provenanceScope,
        "SOURCE_AST_COUNTERFACTUAL_TO_LOCAL_HARDHAT_EVM");
    const x=caseResult.actual;
    let status:string;
    if(caseResult.challengeKind==="ZERO_AMOUNT_BOUNDARY"){
        assert.equal(caseResult.testQuantity,"0");
        const before=BigInt(x.actualNumericBefore),after=BigInt(x.actualNumericAfter);
        assert.equal(x.totalSupplyStrictlyDecreased,after<before);
        const realCounterexample=x.transactionMined===true && after>=before;
        assert.equal(x.interpretation,realCounterexample?
            "OVERGENERALIZED_STRICT_DECREASE_FALSIFIED":
            "OVERGENERALIZATION_NOT_FALSIFIED_BY_THIS_ZERO_CASE");
        if(x.transactionMined){
            assert.equal(x.execution,"MINED_SUCCESSFUL_ZERO_QUANTITY");
            assert.equal(x.receipt?.receiptStatus,1);
            assert.equal(x.receipt?.verification,
                "LOCAL_PROVIDER_BLOCK_TX_AND_RECEIPT_RECHECKED");
            assert.match(x.receipt.txHash,/^0x[0-9a-f]{64}$/i);
            assert.match(x.receipt.blockHash,/^0x[0-9a-f]{64}$/i);
            assert.match(x.receipt.contractCodeKeccak256,/^0x[0-9a-f]{64}$/i);
            assert.match(x.receipt.transactionTo,/^0x[0-9a-f]{40}$/i);
            assert.match(x.receipt.caller,/^0x[0-9a-f]{40}$/i);
            assert.equal(x.receipt.transactionTo.toLowerCase(),
                (caseResult.operation==="BURN_UNDERLYING"
                    ?originalEvm.fixtureAddresses.asset
                    :originalEvm.fixtureAddresses.vault).toLowerCase());
            assert.equal(x.allTrackedStateUnchanged,true,
                "Zero-value successful call altered protected tracked state");
        }else{
            assert.equal(x.execution,"ZERO_QUANTITY_REVERTED");
            assert.equal(x.receipt,null);
        }
        status=realCounterexample?"REFUTED_OVERBROAD_CLAIM":
            "NO_COUNTEREXAMPLE_ON_ZERO_QUANTITY";
    }else{
        assert.equal(caseResult.challengeKind,"ABOVE_OWNED_BALANCE");
        const amount=BigInt(x.attemptedAmount),
            balance=BigInt(x.previousOwnedBalance);
        assert.equal(amount,balance+1n);
        assert.equal(caseResult.testQuantity,amount.toString());
        assert.equal(x.transactionMined,false);
        assert.equal(x.receipt,null);
        assert.equal(x.allTrackedStateUnchanged,true);
        const rejected=x.execution==="UNMINED_EVM_CALLSTATIC_REVERT";
        assert.equal(x.interpretation,rejected?
            "OVERGENERALIZED_UNCONDITIONAL_EXECUTABILITY_FALSIFIED":
            "UNCONDITIONAL_EXECUTABILITY_NOT_FALSIFIED_BY_THIS_CASE");
        status=rejected?"EXECUTABILITY_OVERCLAIM_REFUTED":
            "OVERBALANCE_CALL_DID_NOT_REVERT";
    }
    checked.push({caseId:predicted.caseId,
      originalScopedPredictionId:predicted.originalScopedPredictionId,
      scientificChallengeStatus:status,
      role:predicted.operation,quantityRule:predicted.quantityRule,
      resultStatus:x.execution,
      receiptScope:x.transactionMined===true?"LOCAL_PROVIDER_CHECKED":
        "UNMINED_READ_ONLY_OR_REVERTED",
      originalAstHypothesisFalsified:false,
      overallCompatibility:"NOT_EVALUATED"});
}
const zeroRefuted=checked.filter(x=>x.scientificChallengeStatus==="REFUTED_OVERBROAD_CLAIM").length;
const overbalanceRefuted=checked.filter(x=>x.scientificChallengeStatus==="EXECUTABILITY_OVERCLAIM_REFUTED").length;
assert.equal(zeroRefuted,2,"Both reviewed pinned zero-value fixtures should be counterexamples");
assert.equal(overbalanceRefuted,2,"Both reviewed overbalance negatives should revert");
const refinedHypotheses=originalPlan.predictions.map((p:any)=>{
    const actualPositive=positive.observations.find((x:any)=>
        x.predictionId===p.predictionId&&x.experimentalOperation===p.operation);
    assert(actualPositive&&actualPositive.strictNumericRelationHolds===true,
        "No verified positive-quantity baseline for refinement");
    const zero=checked.find(x=>x.originalScopedPredictionId===p.predictionId&&
        x.quantityRule==="ZERO");
    const over=checked.find(x=>x.originalScopedPredictionId===p.predictionId&&
        x.quantityRule==="OWNED_TOKEN_BALANCE_PLUS_ONE");
    assert(zero&&over&&zero.scientificChallengeStatus==="REFUTED_OVERBROAD_CLAIM"&&
        over.scientificChallengeStatus==="EXECUTABILITY_OVERCLAIM_REFUTED");
    const originCase=evm.cases.find((x:any)=>x.caseId===zero.caseId);
    assert(originCase.actual.transactionMined===true&&
        originCase.actual.allTrackedStateUnchanged===true);
    return {
      researchRevisionId:"SCI-REV-"+hash(Buffer.from(
        originalPlan.originHypothesisId+"|"+p.predictionId+"|"+
        hash(experimentBytes))).slice(0,24),
      originalAstHypothesisId:originalPlan.originHypothesisId,
      scopedPredictionId:p.predictionId,
      participant:p.participant,publicEntrypoint:p.publicEntrypoint,
      sourceRevision:p.sourceRevision,sourceSha256:p.stateSourceSha256,
      epistemicStatus:"CONDITIONALLY_SUPPORTED_WITH_FALSIFIED_OVERGENERALIZATIONS",
      originalAstFindingStillValid:true,
      revisedStatement:
        "In the pinned local fixture, one eligible-owner "+
        p.publicEntrypoint+" transaction of positive quantity decreased "+
        p.stateVar+"; the successful zero-quantity boundary invocation did not decrease it; "+
        "an amount above owned balance reverted in an unmined EVM call simulation.",
      supportedObservation:{
        strictlyDecreasedForPositiveAmount:true,
        localMinedReceipt:actualPositive.witness.transactionHash,
        measuredBefore:actualPositive.before,
        measuredAfter:actualPositive.after
      },
      falsifyingObservations:[
        {caseId:zero.caseId,claimRefuted:
          "EVERY_SUCCESSFUL_CALL_STRICTLY_DECREASES_TOTAL_SUPPLY",
          localMinedReceipt:originCase.actual.receipt.txHash},
        {caseId:over.caseId,claimRefuted:
          "PUBLIC_ENTRYPOINT_ALWAYS_EXECUTABLE",
          unminedCallStaticRevert:true}
      ],
      unprovenQuestions:[
        "Does a separate, fully coordinated operation preserve atomicity across both contracts?",
        "Are the same semantics preserved under different implementation revisions, modifiers, permissions or asset behavior?",
        "Do adversarial reentrant callbacks and hostile counterparties preserve all relevant invariants?"
      ],
      humanReviewRequired:true,
      globalCompatibilityVerdict:"NOT_EVALUATED",
      candidateAdmission:"NOT_ADMITTED"
    };
});
assert.equal(refinedHypotheses.length,2);
const out={
 schemaVersion:"OECL_INDEPENDENT_AST_SELF_FALSIFICATION_REVIEW_V1",
 sourceHypothesisId:originalPlan.originHypothesisId,
 sourceGraphSha256:source.graphSha256,
 positiveEvmArtifactSha256:hash(read("ast-hypothesis-experiment")),
 counterfactualPlanSha256:hash(challengedPlanBytes),
 counterfactualEvmArtifactSha256:hash(experimentBytes),
 scope:"SCIENCE_REFUTES_OVERBROAD_INFERENCE_NOT_ORIGINAL_SCOPED_AST_OBSERVATION",
 reviewStatus:"TWO_OVERGENERALIZATIONS_CONDITIONALLY_FALSIFIED_PER_SUPPORTED_OPERATION",
 boundaryCounterexamples:zeroRefuted,
 deniedUnconditionalExecutions:overbalanceRefuted,
 cases:checked,
 refinedHypotheses,
 scientificVerdict:"INCONCLUSIVE",
 globalCompatibilityVerdict:"NOT_EVALUATED",
 candidateAdmission:"NOT_ADMITTED",
 receiptAuthentication:"NOT_PERFORMED_BY_THIS_REPLAY",
 limitations:[
   "No EVM execution in this reviewer: independently checks prior exact-run local provider observations and source-anchored preregistration.",
   "Zero-amount successful execution challenges an overly general strict-decrease claim, not the original conditional positive-amount AST hypothesis.",
   "An unmined callStatic revert demonstrates a negative invocation under its specific state but not a globally uncallable method.",
   "Not automatic unrestricted formal verification, sandbox safety or a mainnet consensus receipt proof."
 ]
};
mkdirSync(dirname(destination),{recursive:true});
writeFileSync(destination,JSON.stringify(out,null,2)+"\n");
console.log("OECL_INDEPENDENT_AST_SELF_FALSIFICATION_REPLAY_PASS",JSON.stringify({
 sourceHypothesisId:out.sourceHypothesisId,
 zeroValueCounterexamples:zeroRefuted,
 overbalanceReverts:overbalanceRefuted,
 refinedHypotheses:refinedHypotheses.length,
 globalCompatibilityVerdict:out.globalCompatibilityVerdict
}));
