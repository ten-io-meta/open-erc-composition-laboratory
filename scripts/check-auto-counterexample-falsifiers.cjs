"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path");
const {review}=require("./review-auto-counterexample-proposal.cjs");
const root=path.resolve(process.argv[2]||"");assert(process.argv[2],"USAGE: <archived-witness-dir>");
const p=JSON.parse(fs.readFileSync(path.join(root,"autogenerated-counterexample-proposal.json")));
const w=JSON.parse(fs.readFileSync(path.join(root,"autogenerated-counterexample-witness.json")));
assert.equal(review(p,w).archivedReceiptsReconciled,14);
const planMutations=[
 ["grant forged approval",p=>p.requestedAuthorizations[0].granted=true],
 ["enable public dispatch",p=>p.executionAuthorized=true],
 ["claim executed source plan",p=>p.evmExecuted=true],
 ["forge candidate admission",p=>p.candidateAdmission="ADMITTED"],
 ["modify donor selection",p=>p.selection.donation=20],
 ["forge provenance",p=>p.provenance.solmateRevision="a".repeat(40)],
 ["forge model review",p=>p.economicPrior="AUTO_INFERRED"],
 ["unbound extra command",p=>p.experimentProgram.push({kind:"TRANSFER_TO_ATTACKER"})]
];
let planRejected=0;
for(const [name,mutate] of planMutations){
 const changed=structuredClone(p);mutate(changed);
 assert.throws(()=>review(changed,w),"FORGED_AUTONOMOUS_PROPOSAL_ACCEPTED:"+name);
 planRejected++;
}
