"use strict";
const assert=require("node:assert/strict");
const crypto=require("node:crypto");
const {buildPlan,conclude}=require("../laboratory/scientific-open-source-worker/CapabilityGatedScienceCycle.cjs");
const hash=x=>crypto.createHash("sha256").update(x).digest("hex");
const canonical=x=>hash(JSON.stringify(x));
const alpha="a".repeat(64),beta="b".repeat(64),gamma="c".repeat(64);
const hypothesisId="AST-HYP-"+"d".repeat(24);
const b=x=>Buffer.from(JSON.stringify(x,null,2)+"\n");
const source=(id,revision,sha)=>({id,kind:"openzeppelin",revision,sourceSha256:sha,
  sourceUnit:"pinned/"+id,repository:"@openzeppelin/contracts"});
const make=(pair=["ERC-8098","ERC-4626"],withHypothesis=true)=>{
  const graph={schemaVersion:"OECL_SOLIDITY_COMPILER_AST_GRAPH_V1",mock:"SOURCE_ONLY_FIXTURE"};
  const selected=[source(pair[0],"rev-a",alpha),source(pair[1],"4.9.6",beta)];
  const evidence=selected.map((s,i)=>({
    participant:s.id,
    publicEntrypoint:{name:i===0?"burn":"redeem",sourceSha256:s.sourceSha256},
    stateDecrease:{state:"_totalSupply",sourceSha256:s.sourceSha256},
    callPath:[i+1]
  }));
  const hypothesis={hypothesisId,kind:"POTENTIAL_COUPLED_STATE_DECREASE",
    status:"SOURCE_ONLY_UNEVALUATED",scientificVerdict:"INCONCLUSIVE",
    candidateAdmission:"NOT_ADMITTED",evidence};
  const discovery={schemaVersion:"OECL_GENERIC_AST_HYPOTHESES_V1",
    verdict:"INCONCLUSIVE",candidateAdmission:"NOT_ADMITTED",
    errors:[],sourceGraphSha256:canonical(graph),
    hypotheses:withHypothesis?[hypothesis]:[]};
  const feasibility={sourceGraphSha256:canonical(graph),discoverySha256:canonical(discovery),
    hypotheses:withHypothesis?[{hypothesisId,pathScreen:"NOT_PROVEN_EXECUTABLE"}]:[]};
  const report={schemaVersion:"OECL_OPEN_GENERIC_AST_RESULT_V1",sourceOnly:true,
    evmExecuted:false,scientificVerdict:"INCONCLUSIVE",candidateAdmission:"NOT_ADMITTED",
    selected,graphSha256:canonical(graph),
    hypothesisArtifactSha256:canonical(discovery),
    pathFeasibilityArtifactSha256:canonical(feasibility),
    hypotheses:discovery.hypotheses};
  const predictions=evidence.map((e,i)=>({
    predictionId:"PRED-"+i,parentAstHypothesisId:hypothesisId,
    participant:selected[i].id,participantSide:i===0?"A":"B",
    operation:i===0?"BURN_UNDERLYING":"REDEEM_SHARES",
    publicEntrypoint:i===0?"burn":"redeem",stateVar:"_totalSupply",
    stateSourceSha256:e.stateDecrease.sourceSha256,
    publicEntrypointSourceSha256:e.publicEntrypoint.sourceSha256,
    sourceRevision:selected[i].revision,sourceRootSha256:selected[i].sourceSha256,
    callPath:e.callPath,requiredNumericRelation:"STRICTLY_LESS_THAN"}));
  const original={schemaVersion:"OECL_AUTOGENERATED_PINNED_AST_HYPOTHESIS_EXPERIMENT_V1",
    originatedBy:"OECL_GENERIC_AST_HYPOTHESES_V1",
    originHypothesisId:hypothesisId,originHypothesisKind:"POTENTIAL_COUPLED_STATE_DECREASE",
    experimentId:"synthetic",preparedBeforeEvmDeployment:true,
    sourceOnlyBeforeExperiment:true,evmExecuted:false,
    provenance:{reportSha256:hash(b(report)),discoverySha256:hash(b(discovery)),
      graphSha256:report.graphSha256,sources:selected},predictions};
  const originalBytes=b(original);
  const challenges={schemaVersion:"OECL_AST_SELF_FALSIFICATION_PLAN_V1",
    originHypothesisId:hypothesisId,experimentId:"synthetic",
    sourcePlanSha256:hash(originalBytes),sourceGraphSha256:report.graphSha256,
    generatedBeforeEvmDeployment:true,emulatedEvmOrReceipt:false,
    compatibilityVerdict:"NOT_EVALUATED",candidateAdmission:"NOT_ADMITTED",
    challenges:predictions.flatMap(p=>[
      {caseId:p.predictionId+"-zero",originalScopedPredictionId:p.predictionId,
        originHypothesisId:hypothesisId,operation:p.operation,
        sourceSha256:p.stateSourceSha256,sourceRevision:p.sourceRevision,
        challengeKind:"ZERO_AMOUNT_BOUNDARY",quantityRule:"ZERO",
        status:"CHALLENGE_PROPOSED_NOT_EVM_TESTED",
        contestedGeneralization:"EVERY_SUCCESSFUL_CALL_STRICTLY_DECREASES_TOTAL_SUPPLY"},
      {caseId:p.predictionId+"-over",originalScopedPredictionId:p.predictionId,
        originHypothesisId:hypothesisId,operation:p.operation,
        sourceSha256:p.stateSourceSha256,sourceRevision:p.sourceRevision,
        challengeKind:"ABOVE_OWNED_BALANCE",quantityRule:"OWNED_TOKEN_BALANCE_PLUS_ONE",
        status:"CHALLENGE_PROPOSED_NOT_EVM_TESTED",
        contestedGeneralization:"PUBLIC_ENTRYPOINT_ALWAYS_EXECUTABLE"}
    ])};
  return {graph,discovery,feasibility,report,original,challenges,
    reportBytes:b(report),discoveryBytes:b(discovery),
    originalBytes,challengeBytes:b(challenges)};
};
const input=make();
const ready=buildPlan(input);
assert.equal(ready.workflowStatus,"REVIEWED_LOCAL_EVM_PROTOCOL_PREREGISTERED");
assert.equal(ready.fixture.ready,true);
assert.equal(ready.localEvmExecuted,false);
assert.equal(ready.compatibilityVerdict,"NOT_EVALUATED");
assert.equal(ready.candidateAdmission,"NOT_ADMITTED");
assert.equal(ready.proposals.length,1);
assert.equal(ready.fixture.testIds.length,4);
assert.equal(buildPlan({...input,original:null,challenges:null}).workflowStatus,
  "BLOCKED_REVIEWED_ADAPTER_REQUIRED");
assert.equal(buildPlan(make(["ERC-4626","ERC-20"])).fixture.ready,false);
assert.equal(buildPlan(make(["ERC-20","ERC-721"],false)).workflowStatus,
  "NO_AST_HYPOTHESIS_OBSERVED");
const tampered=make();tampered.report.graphSha256=alpha;
assert.throws(()=>buildPlan(tampered),/Expected values to be strictly equal/);
const spoofed=make();spoofed.challenges.challenges[1].caseId=
  spoofed.challenges.challenges[0].caseId;
assert.throws(()=>buildPlan(spoofed),/true|false|Expected/);
const forged=make();forged.original.predictions[0].stateSourceSha256=gamma;
assert.throws(()=>buildPlan(forged),/Expected values to be strictly equal/);
const noEvm=conclude({plan:ready,review:null});
assert.equal(noEvm.cycleStatus,"UNRESOLVED");
assert.equal(noEvm.evmEvidenceAdmitted,false);
const positiveBytes=b({witness:"fake for regression only"});
const counterfactualBytes=b({witness:"fake for regression only"});
const originalBytes=input.originalBytes,challengeBytes=input.challengeBytes;
const signed="0x"+"1".repeat(64),other="0x"+"2".repeat(64);
const refined=input.original.predictions.map(p=>({
  originalAstHypothesisId:hypothesisId,scopedPredictionId:p.predictionId,
  originalAstFindingStillValid:true,
  epistemicStatus:"CONDITIONALLY_SUPPORTED_WITH_FALSIFIED_OVERGENERALIZATIONS",
  supportedObservation:{strictlyDecreasedForPositiveAmount:true,
    localMinedReceipt:signed,measuredBefore:"100",measuredAfter:"90"},
  falsifyingObservations:[
    {caseId:p.predictionId+"-zero",
      claimRefuted:"EVERY_SUCCESSFUL_CALL_STRICTLY_DECREASES_TOTAL_SUPPLY",
      localMinedReceipt:other},
    {caseId:p.predictionId+"-over",
      claimRefuted:"PUBLIC_ENTRYPOINT_ALWAYS_EXECUTABLE",
      unminedCallStaticRevert:true}
  ]
}));
const review={schemaVersion:"OECL_INDEPENDENT_AST_SELF_FALSIFICATION_REVIEW_V1",
  sourceHypothesisId:hypothesisId,
  sourceGraphSha256:ready.provenance.graphSha256,
  counterfactualPlanSha256:hash(challengeBytes),
  positiveEvmArtifactSha256:hash(positiveBytes),
  counterfactualEvmArtifactSha256:hash(counterfactualBytes),
  scope:"SCIENCE_REFUTES_OVERBROAD_INFERENCE_NOT_ORIGINAL_SCOPED_AST_OBSERVATION",
  scientificVerdict:"INCONCLUSIVE",globalCompatibilityVerdict:"NOT_EVALUATED",
  candidateAdmission:"NOT_ADMITTED",receiptAuthentication:"NOT_PERFORMED_BY_THIS_REPLAY",
  cases:input.challenges.challenges.map(c=>({
    caseId:c.caseId,scientificChallengeStatus:c.challengeKind==="ZERO_AMOUNT_BOUNDARY"?
      "REFUTED_OVERBROAD_CLAIM":"EXECUTABILITY_OVERCLAIM_REFUTED"
  })),refinedHypotheses:refined};
const args={plan:ready,review,positiveBytes,counterfactualBytes,
  originalBytes,challengeBytes};
const conclusion=conclude(args);
assert.equal(conclusion.cycleStatus,"CONTROLLED_LOCAL_EVM_AND_REPLAY_COMPLETE");
assert.equal(conclusion.scopedConclusions.length,2);
assert.equal(conclusion.evmEvidenceAdmitted,true);
assert(conclusion.scopedConclusions.every(p=>p.originalAstHypothesisFalsified===false));
assert.equal(conclusion.compatibilityVerdict,"NOT_EVALUATED");
assert.throws(()=>conclude({...args,positiveBytes:b("tampered")}),
  /Expected values to be strictly equal/);
assert.throws(()=>conclude({...args,review:{...review,
  globalCompatibilityVerdict:"COMPATIBLE"}}),/Expected values to be strictly equal/);
assert.throws(()=>conclude({...args,review:{...review,
  refinedHypotheses:[refined[0],refined[0]]}}),/Duplicate or substituted prediction/);
assert.throws(()=>conclude({...args,review:{...review,
  refinedHypotheses:[{...refined[0],
    supportedObservation:{...refined[0].supportedObservation,
      measuredAfter:"110"}},refined[1]]}}),/false|true/);
console.log("OECL_CAPABILITY_GATED_SCIENTIFIC_CYCLE_ADVERSARIAL_REGRESSION_PASS",
  "blocked/no-hypothesis/preregistered/scoped/receipt-hash/forgery");
