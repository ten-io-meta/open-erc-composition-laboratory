 const forged=structuredClone(r);mutation(forged);
 const res=compareEvidence(p,w,forged);
 assert.equal(res.accepted,false,"REPLAY_MUTATION_ACCEPTED:"+label);
 assert.equal(res.status,"EVIDENCE_DISAGREEMENT_REQUIRES_INVESTIGATION");
